function escapeHtml(value) {
    return String(value).replace(/[&<>"']/g, character => ({
        '&': '&amp;',
        '<': '&lt;',
        '>': '&gt;',
        '"': '&quot;',
        "'": '&#39;'
    }[character]));
}

function escapeHtmlWithBreaks(value) {
    return String(value)
        .split(/<br\s*\/?>/i)
        .map(escapeHtml)
        .join('<br>');
}

function renderNewsVersion(news, device) {
    const content = news[device];

    return `
        <div class="NewsCardVersion NewsCardVersion--${device}">
            <div class="NewsImageFrame NewsImageFrame--${device}">
                <img src="${escapeHtml(news.image)}" class="imgNewsCard" alt="">
            </div>
            <div class="NewsCardDate exLight">${escapeHtml(content.date)}</div>
            <div class="NewsCardName bold">${escapeHtmlWithBreaks(content.title)}</div>
            <div class="NewsCardDesc regular">${escapeHtmlWithBreaks(content.description)}</div>
        </div>`;
}

